/* ============================================================
   Build the en / ja / ko static pages from index.html + i18n.js.

   index.html is the ONLY source of Chinese copy. Every language page
   is fully translated HTML: it renders correctly even with JS off,
   has its own URL for sharing, and needs no runtime translation.

   Run:  node scripts/build-i18n.mjs
   Then: node scripts/verify-i18n.mjs
   ============================================================ */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://dujeongil-galaxy.github.io/a-reason-for-korea/';
const LANGS = ['en', 'ja', 'ko'];
const HTML_LANG = { zh: 'zh-CN', en: 'en', ja: 'ja', ko: 'ko' };
const ATTR_TARGETS = new Set(['aria-label', 'placeholder', 'content', 'alt']);

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/* --- load the browser-style dictionary inside a VM sandbox --- */
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'assets/i18n.js'), 'utf8'), sandbox);
const I18N = sandbox.window.SITE_I18N;
if (!I18N) throw new Error('i18n.js did not define window.SITE_I18N');

const source = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const missing = [];

/* --- 1. translate innerHTML of every [data-i18n] element --- */
function translateNodes(html, dict) {
  return html.replace(
    /<([a-zA-Z0-9]+)\b([^>]*\bdata-i18n="([^"]+)"[^>]*)>([\s\S]*?)<\/\1>/g,
    (match, tag, attrs, key) => {
      if (!Object.prototype.hasOwnProperty.call(dict, key)) {
        missing.push(key);
        return match;
      }
      return '<' + tag + attrs + '>' + dict[key] + '</' + tag + '>';
    }
  );
}

/* --- 2. translate pointed-at attributes (aria-label / placeholder / content) --- */
function translateAttrs(html, dict) {
  return html.replace(/<([a-zA-Z0-9]+)\b([^>]*)>/g, (match, tag, attrs) => {
    let out = attrs;
    for (const m of attrs.matchAll(/data-i18n-([a-z-]+)="([^"]+)"/g)) {
      const target = m[1];
      const key = m[2];
      if (!ATTR_TARGETS.has(target)) continue;          // canonical / og:url handled below
      if (!Object.prototype.hasOwnProperty.call(dict, key)) {
        missing.push(key);
        continue;
      }
      /* Match a real attribute only: `alt="..."`, never the tail of
         `data-i18n-alt="..."`. Keeping this independent of attribute
         order is what makes adding a new translatable attribute safe. */
      const re = new RegExp('(^|\\s)' + esc(target) + '="[^"]*"');
      const val = target + '="' + dict[key] + '"';
      out = re.test(out)
        ? out.replace(re, (_m, lead) => lead + val)
        : out + ' ' + val;
    }
    return '<' + tag + out + '>';
  });
}

/* --- 3. language switch links + current state --- */
function rewriteLangLinks(html, lang) {
  return html.replace(/<a\s+data-lang-link="([a-z]+)"[^>]*>/g, (match, code) => {
    const href = code === 'zh' ? '../' : '../' + code + '/';
    const current = code === lang ? ' class="is-current" aria-current="page"' : '';
    return '<a data-lang-link="' + code + '" href="' + href + '" lang="' +
      (code === 'zh' ? 'zh' : code) + '"' + current + '>';
  });
}

for (const lang of LANGS) {
  const dict = I18N[lang];
  if (!dict || !dict.html || !dict.attr) throw new Error('missing dictionary for ' + lang);
  const pageUrl = SITE + lang + '/';

  let out = translateNodes(source, dict.html);
  out = translateAttrs(out, dict.attr);
  out = rewriteLangLinks(out, lang);

  out = out.replace(/<html lang="[^"]*">/, '<html lang="' + HTML_LANG[lang] + '">');
  out = out.replace(/<body data-lang="[^"]*">/, '<body data-lang="' + lang + '">');

  /* per-language canonical + og:url */
  out = out.replace(/(<link rel="canonical" href=")[^"]*(")/, '$1' + pageUrl + '$2');
  out = out.replace(/(<meta property="og:url" content=")[^"]*(")/, '$1' + pageUrl + '$2');

  /* relative assets, now one directory deeper */
  out = out.replace(/\b(href|src)="(assets\/|favicon\.svg)/g, '$1="../$2');

  /* provenance banner */
  out = out.replace(
    '<!DOCTYPE html>',
    '<!DOCTYPE html>\n<!-- Generated by scripts/build-i18n.mjs from index.html. Do not edit by hand. -->'
  );

  const dir = path.join(ROOT, lang);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), out, 'utf8');
  console.log(lang + '/index.html  ' + Buffer.byteLength(out) + ' bytes  ' + Object.keys(dict.html).length + ' translated nodes');
}

if (missing.length) {
  console.error('MISSING KEYS: ' + [...new Set(missing)].join(', '));
  process.exit(1);
}
console.log('build done.');
